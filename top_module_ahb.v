        .start_addr(start_addr),
        .burst_mode(burst_mode),
        .transfer_size(transfer_size),
        .write_en(write_en),
        .write_data(write_data),
        .read_data(read_data)
    );

    decoder_ahb u_decoder (
        .HADDR(HADDR),
        .HREADY(HREADY_IN_TO_SLAVES), 
        
        .HSEL_SLAVE1(HSEL_S0),
        .HSEL_SLAVE2(HSEL_S1),
        .HSEL_SLAVE3(HSEL_S2),
