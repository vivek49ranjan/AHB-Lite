    wire [31:0] HWDATA;
    wire HWRITE;
    wire [1:0] HTRANS;
    wire [2:0] HBURST;
    wire [2:0] HSIZE;
    
    wire HREADY_OUT_TO_MASTER; 
    wire HREADY_IN_TO_SLAVES;  
    
    wire HRESP;
    wire [31:0] HRDATA;

    wire HSEL_S0, HSEL_S1, HSEL_S2, HSEL_S3, HSEL_S4, HSEL_S5, HSEL_S6, HSEL_S7, HSEL_DEF;

    wire [31:0] SLAVE0_HRDATA, SLAVE1_HRDATA, SLAVE2_HRDATA, SLAVE3_HRDATA;
