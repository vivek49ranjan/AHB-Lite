    wire SLAVE4_READYOUT, SLAVE5_READYOUT, SLAVE6_READYOUT, SLAVE7_READYOUT;
    wire DEF_READYOUT;

    assign HREADY_IN_TO_SLAVES = SLAVE0_READYOUT | SLAVE1_READYOUT | SLAVE2_READYOUT | SLAVE3_READYOUT | 
                                 SLAVE4_READYOUT | SLAVE5_READYOUT | SLAVE6_READYOUT | SLAVE7_READYOUT | 
