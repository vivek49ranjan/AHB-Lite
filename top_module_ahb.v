    master_ahb u_master (
        .HCLK(HCLK),
        .HRESETn(HRESETn),
        .HREADY(HREADY_OUT_TO_MASTER), 
        .HRESP(HRESP),
        .HRDATA(HRDATA),

        .HADDR(HADDR),
        .HWDATA(HWDATA),
        .HWRITE(HWRITE),
        .HTRANS(HTRANS),
        .HBURST(HBURST),
        .HSIZE(HSIZE),

